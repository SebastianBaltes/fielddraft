/**
 * P3 — Code-First Export: React Three Fiber.
 *
 * Generates a self-contained `.tsx` component file from a FieldDraft
 * assembly or part studio. The output is a React Three Fiber scene
 * graph with `<group>` transforms for each part/body and props for
 * revolute joint angles.
 *
 * Usage: exportR3F(assembly) → string (TSX source code)
 *
 * The exported component expects GLTF mesh files alongside it.
 * A separate exportMeshesAsGLB() function generates those files.
 */

import type { AssemblyDocument } from "./assembly";

function sanitizeName(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/^(\d)/, "_$1")
    .replace(/_+/g, "_");
}

function pascalCase(name: string): string {
  return sanitizeName(name)
    .split("_")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

export function exportR3F(assembly: AssemblyDocument): string {
  const componentName = pascalCase(assembly.name) || "Assembly";
  const revMates = assembly.mates.filter((m) => m.type === "revolute");
  const propNames = revMates.map((_m, i) => `joint${i}Angle`);

  const propsInterface = revMates.length > 0
    ? `interface ${componentName}Props {\n${propNames.map((n) => `  ${n}?: number;`).join("\n")}\n}\n\n`
    : "";

  const propsArg = revMates.length > 0
    ? `{ ${propNames.map((n) => `${n} = 0`).join(", ")} }: ${componentName}Props`
    : "";

  const lines: string[] = [];
  lines.push(`// Generated by FieldDraft — Code-First Export`);
  lines.push(`// ${new Date().toISOString()}`);
  lines.push(``);
  lines.push(`import { useGLTF } from "@react-three/drei";`);
  lines.push(`import * as THREE from "three";`);
  lines.push(``);
  lines.push(propsInterface);
  lines.push(`export function ${componentName}(${propsArg}) {`);

  for (let i = 0; i < assembly.parts.length; i++) {
    const part = assembly.parts[i];
    const varName = `part${i}`;
    const meshFile = `./${sanitizeName(part.name)}.glb`;

    lines.push(`  // ${part.name}`);
    lines.push(`  const ${varName} = useGLTF("${meshFile}");`);
  }

  lines.push(``);
  lines.push(`  return (`);
  lines.push(`    <group>`);

  for (let i = 0; i < assembly.parts.length; i++) {
    const part = assembly.parts[i];
    const varName = `part${i}`;
    const [tx, ty, tz] = part.transform.translate;
    const [rx, ry, rz] = part.transform.rotate.map((d) => (d * Math.PI) / 180);

    const revMate = revMates.find((m) => m.connectorB.partId === part.id);
    const revIdx = revMate ? revMates.indexOf(revMate) : -1;

    const rotY = revIdx >= 0
      ? `${ry.toFixed(4)} + (${propNames[revIdx]} * Math.PI) / 180`
      : ry.toFixed(4);

    lines.push(`      <group`);
    lines.push(`        position={[${tx.toFixed(2)}, ${ty.toFixed(2)}, ${tz.toFixed(2)}]}`);
    lines.push(`        rotation={[${rx.toFixed(4)}, ${rotY}, ${rz.toFixed(4)}]}`);
    lines.push(`      >`);
    lines.push(`        <primitive object={${varName}.scene.clone()} />`);
    lines.push(`      </group>`);
  }

  lines.push(`    </group>`);
  lines.push(`  );`);
  lines.push(`}`);
  lines.push(``);

  // Add useGLTF.preload calls
  for (const part of assembly.parts) {
    const meshFile = `./${sanitizeName(part.name)}.glb`;
    lines.push(`useGLTF.preload("${meshFile}");`);
  }
  lines.push(``);

  return lines.join("\n");
}

/**
 * Generate a downloadable TSX file from the assembly.
 */
export function downloadR3FExport(assembly: AssemblyDocument): void {
  const code = exportR3F(assembly);
  const blob = new Blob([code], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${sanitizeName(assembly.name) || "assembly"}.tsx`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
